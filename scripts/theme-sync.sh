#!/bin/sh
# LovelyRice built-in theme sync. Run by the shell (Hooks.qml) after a theme or wallpaper change, with the colors
# in LR_* environment variables (see Hooks.qml). `lovelyrice sync` runs it through the shell. It writes to
#   ~/.local/state/lovelyrice/generated/
#     foot-colors.ini    colors for NEW foot windows   (copied to ~/.config/foot/lovelyrice-colors.ini, which
#                        foot.ini includes: `lovelyrice setup foot`)
#     colors.osc         the same colors as terminal escape codes (shell startup, `lovelyrice colors`)
#     gtk.css            GTK 3 + 4 named colors        (copied to ~/.config/gtk-{3,4}.0/lovelyrice.css, which
#                        your gtk.css imports: `lovelyrice setup gtk`)
#     fastfetch.jsonc    fastfetch config + fastfetch-logo.ansi (the half-block cat in theme colors)
#     logo.svg           the cat logo in theme colors
#     colors.sh          `. colors.sh` gives any script the LR_* colors
# and recolors every running foot terminal in place. It never edits your own config files.

set -u
[ -n "${LR_BG:-}" ] && [ -n "${LR_ACCENT:-}" ] || { echo "theme-sync: needs the LR_* colors; run it with 'lovelyrice sync'" >&2; exit 1; }

here=$(cd "$(dirname "$0")" && pwd)
assets="${LR_ASSETS:-$here/../assets}"
out="${HOME}/.local/state/lovelyrice/generated"
mkdir -p "$out" || exit 1
exec 2>"$out/last-sync.log"

# ---------- helpers ----------
bare() { printf %s "${1#\#}"; }                                  # #rrggbb -> rrggbb
chan() { printf %d "$((0x$(printf %s "${1#\#}" | cut -c"$2-$(($2 + 1))")))"; }   # chan #rrggbb 1|3|5 -> 0..255
sgr() { printf '38;2;%d;%d;%d' "$(chan "$1" 1)" "$(chan "$1" 3)" "$(chan "$1" 5)"; }
rgba() { printf 'rgba(%d,%d,%d,%s)' "$(chan "$1" 1)" "$(chan "$1" 3)" "$(chan "$1" 5)" "$2"; }
lum() { echo $(( (299 * $(chan "$1" 1) + 587 * $(chan "$1" 3) + 114 * $(chan "$1" 5)) / 1000 )); }

# put <file>: stdin -> file; success (0) only when the content changed
put() {
    tmp="$1.tmp.$$"
    cat > "$tmp"
    if [ -f "$1" ] && cmp -s "$tmp" "$1"; then rm -f "$tmp"; return 1; fi
    mv -f "$tmp" "$1"
}

bg=$LR_BG; surface=$LR_SURFACE; fg=$LR_FG; dim=$LR_DIM; accent=$LR_ACCENT; accent2=$LR_ACCENT2; warn=$LR_WARN
light=${LR_LIGHT:-0}
if [ "$(lum "$bg")" -lt "$(lum "$fg")" ]; then dark_ink=$bg; light_ink=$fg; else dark_ink=$fg; light_ink=$bg; fi
ink_on() { if [ "$(lum "$1")" -gt 140 ]; then printf %s "$dark_ink"; else printf %s "$light_ink"; fi; }   # readable text on color $1

# the 16 terminal colors (LR_C0..LR_C15); fall back to something sensible if the shell did not send them
i=0
while [ "$i" -lt 16 ]; do
    eval "v=\${LR_C$i:-}"
    if [ -z "$v" ]; then
        case "$i" in 0) v=$surface ;; 7) v=$fg ;; 8) v=$dim ;; 15) v=$fg ;; 1|9) v=$accent ;; 2|10) v=$accent2 ;; 3|11) v=$warn ;; *) v=$accent ;; esac
    fi
    eval "c$i=\$v"
    i=$((i + 1))
done

# ---------- colors.sh ----------
{
    echo "# generated by LovelyRice theme-sync; source it to get the current theme colors"
    for n in THEME BG SURFACE FG DIM ACCENT ACCENT2 WARN LIGHT; do eval "printf 'export LR_%s=\"%s\"\n' \"$n\" \"\${LR_$n:-}\""; done
    i=0; while [ "$i" -lt 16 ]; do eval "printf 'export LR_C%s=\"%s\"\n' $i \"\$c$i\""; i=$((i + 1)); done
} | put "$out/colors.sh"

# ---------- foot ----------
# foot >= 1.24 wants [colors-dark] / [colors-light] (the plain [colors] section and [cursor] were removed), so write both
{
    echo "# generated by LovelyRice theme-sync - do not edit"
    for sec in colors-dark colors-light; do
        echo "[$sec]"
        echo "foreground=$(bare "$fg")"
        echo "background=$(bare "$bg")"
        i=0; while [ "$i" -lt 8 ]; do eval "echo regular$i=\$(bare \"\$c$i\")"; i=$((i + 1)); done
        i=0; while [ "$i" -lt 8 ]; do eval "echo bright$i=\$(bare \"\$c$((i + 8))\")"; i=$((i + 1)); done
        echo "selection-foreground=$(bare "$bg")"
        echo "selection-background=$(bare "$accent")"
        echo "cursor=$(bare "$bg") $(bare "$accent")"
        echo
    done
} | put "$out/foot-colors.ini"

# foot.ini includes ~/.config/foot/lovelyrice-colors.ini once `lovelyrice setup foot` has created it; keep that file current
foot_inc="${XDG_CONFIG_HOME:-$HOME/.config}/foot/lovelyrice-colors.ini"
[ "${LR_SYNC_FOOT:-1}" != 0 ] && [ -e "$foot_inc" ] && put "$foot_inc" < "$out/foot-colors.ini"

# escape codes: 10 foreground, 11 background, 12 cursor, 4;N palette entries
{
    esc=$(printf '\033')
    printf '%s]10;%s%s\\' "$esc" "$fg" "$esc"
    printf '%s]11;%s%s\\' "$esc" "$bg" "$esc"
    printf '%s]12;%s%s\\' "$esc" "$accent" "$esc"
    i=0; while [ "$i" -lt 16 ]; do eval "printf '%s]4;%s;%s%s\\\\' \"\$esc\" $i \"\$c$i\" \"\$esc\""; i=$((i + 1)); done
} | put "$out/colors.osc"

if [ "${LR_SYNC_FOOT:-1}" != 0 ] && command -v pgrep >/dev/null 2>&1; then
    # every shell running inside a foot window (or a foot --server) is a child of the foot process; write the codes to its tty
    for p in $(pgrep -x foot 2>/dev/null); do ps -o tty= --ppid "$p" 2>/dev/null; done | sort -u | while read -r t; do
        case "$t" in pts/*) [ -w "/dev/$t" ] && ( cat "$out/colors.osc" > "/dev/$t" ) 2>/dev/null & ;; esac
    done
    wait
fi

# ---------- GTK ----------
accent_fg=$(ink_on "$accent"); good=$c2; bad=$c1
if [ "$light" = 1 ]; then shade="rgba(0,0,0,0.07)"; else shade="rgba(0,0,0,0.36)"; fi
border=$(rgba "$fg" 0.15)
{
    echo "/* generated by LovelyRice theme-sync - do not edit (theme: ${LR_THEME:-?}). Imported by gtk.css: lovelyrice setup gtk */"
    # libadwaita (GTK 4) and adw-gtk3
    echo "@define-color accent_color $accent;"
    echo "@define-color accent_bg_color $accent;"
    echo "@define-color accent_fg_color $accent_fg;"
    echo "@define-color destructive_color $bad;"
    echo "@define-color destructive_bg_color $bad;"
    echo "@define-color destructive_fg_color $(ink_on "$bad");"
    echo "@define-color success_color $good;"
    echo "@define-color success_bg_color $good;"
    echo "@define-color success_fg_color $(ink_on "$good");"
    echo "@define-color warning_color $warn;"
    echo "@define-color warning_bg_color $warn;"
    echo "@define-color warning_fg_color $(ink_on "$warn");"
    echo "@define-color error_color $bad;"
    echo "@define-color error_bg_color $bad;"
    echo "@define-color error_fg_color $(ink_on "$bad");"
    echo "@define-color window_bg_color $bg;"
    echo "@define-color window_fg_color $fg;"
    echo "@define-color view_bg_color $bg;"
    echo "@define-color view_fg_color $fg;"
    echo "@define-color headerbar_bg_color $surface;"
    echo "@define-color headerbar_fg_color $fg;"
    echo "@define-color headerbar_border_color $surface;"
    echo "@define-color headerbar_backdrop_color $bg;"
    echo "@define-color headerbar_shade_color $shade;"
    echo "@define-color headerbar_darker_shade_color $shade;"
    echo "@define-color card_bg_color $surface;"
    echo "@define-color card_fg_color $fg;"
    echo "@define-color card_shade_color $shade;"
    echo "@define-color dialog_bg_color $surface;"
    echo "@define-color dialog_fg_color $fg;"
    echo "@define-color popover_bg_color $surface;"
    echo "@define-color popover_fg_color $fg;"
    echo "@define-color popover_shade_color $shade;"
    echo "@define-color sidebar_bg_color $surface;"
    echo "@define-color sidebar_fg_color $fg;"
    echo "@define-color sidebar_backdrop_color $bg;"
    echo "@define-color sidebar_border_color $border;"
    echo "@define-color sidebar_shade_color $shade;"
    echo "@define-color secondary_sidebar_bg_color $bg;"
    echo "@define-color secondary_sidebar_fg_color $fg;"
    echo "@define-color secondary_sidebar_backdrop_color $bg;"
    echo "@define-color secondary_sidebar_shade_color $shade;"
    echo "@define-color thumbnail_bg_color $surface;"
    echo "@define-color thumbnail_fg_color $fg;"
    echo "@define-color shade_color $shade;"
    echo "@define-color scrollbar_outline_color $shade;"
    # classic GTK 3 Adwaita names
    echo "@define-color theme_bg_color $bg;"
    echo "@define-color theme_fg_color $fg;"
    echo "@define-color theme_base_color $bg;"
    echo "@define-color theme_text_color $fg;"
    echo "@define-color theme_selected_bg_color $accent;"
    echo "@define-color theme_selected_fg_color $accent_fg;"
    echo "@define-color theme_unfocused_bg_color $bg;"
    echo "@define-color theme_unfocused_fg_color $fg;"
    echo "@define-color theme_unfocused_base_color $bg;"
    echo "@define-color theme_unfocused_text_color $fg;"
    echo "@define-color theme_unfocused_selected_bg_color $accent;"
    echo "@define-color theme_unfocused_selected_fg_color $accent_fg;"
    echo "@define-color insensitive_bg_color $surface;"
    echo "@define-color insensitive_fg_color $dim;"
    echo "@define-color insensitive_base_color $bg;"
    echo "@define-color theme_unfocused_insensitive_bg_color $surface;"
    echo "@define-color borders $border;"
    echo "@define-color unfocused_borders $border;"
    echo "@define-color warning_color $warn;"
    echo "@define-color error_color $bad;"
    echo "@define-color success_color $good;"
    echo "@define-color link_color $accent2;"
    echo "@define-color link_visited_color $accent2;"
    echo "@define-color content_view_bg $bg;"
    echo "@define-color text_view_bg $bg;"
} | put "$out/gtk.css" && gtk_changed=1 || gtk_changed=0
# ~/.config/gtk-{3,4}.0/lovelyrice.css exist once `lovelyrice setup gtk` has run (gtk.css imports them)
if [ "${LR_SYNC_GTK:-1}" != 0 ]; then
    for v in 3.0 4.0; do
        f="${XDG_CONFIG_HOME:-$HOME/.config}/gtk-$v/lovelyrice.css"
        [ -e "$f" ] && put "$f" < "$out/gtk.css" && gtk_changed=1
    done
fi

if [ "${LR_SYNC_GTK:-1}" != 0 ] && command -v gsettings >/dev/null 2>&1; then
    s=org.gnome.desktop.interface
    if [ "$light" = 1 ]; then scheme=prefer-light; else scheme=prefer-dark; fi
    gsettings set "$s" color-scheme "$scheme" 2>/dev/null
    # running GTK apps only re-read their CSS when the GTK theme changes: bounce it once, and only if the colors changed
    # and `lovelyrice setup gtk` has linked the file in
    if [ "$gtk_changed" = 1 ] && { [ -e "${XDG_CONFIG_HOME:-$HOME/.config}/gtk-4.0/lovelyrice.css" ] || [ -e "${XDG_CONFIG_HOME:-$HOME/.config}/gtk-3.0/lovelyrice.css" ]; }; then
        cur=$(gsettings get "$s" gtk-theme 2>/dev/null)
        cur=${cur#\'}; cur=${cur%\'}
        if [ -n "$cur" ]; then
            tmp=HighContrast; [ "$cur" = HighContrast ] && tmp=Adwaita
            gsettings set "$s" gtk-theme "$tmp" 2>/dev/null
            sleep 0.25
            gsettings set "$s" gtk-theme "$cur" 2>/dev/null
        fi
    fi
fi

# ---------- logo.svg ----------
if [ -f "$assets/logo.svg" ]; then
    sed -e 's/#e5334b/@A@/g' -e 's/#8b5cf6/@B@/g' "$assets/logo.svg" | sed -e "s/@A@/$accent/g" -e "s/@B@/$accent2/g" | put "$out/logo.svg"
fi

# ---------- fastfetch ----------
cols=0; rows=0
if [ -f "$assets/cat.pix" ]; then
    awk -v c1="$(sgr "$accent")" -v c2="$(sgr "$accent2")" '
        { row[NR] = $0 }
        END {
            esc = sprintf("%c", 27)
            n = NR
            for (y = 1; y < n; y += 2) {
                line = ""
                w = length(row[y])
                for (x = 1; x <= w; x++) {
                    t = substr(row[y], x, 1); b = substr(row[y + 1], x, 1)
                    ct = (t == "1") ? c1 : c2
                    cb = (b == "1") ? c1 : c2
                    if (t == "0" && b == "0")      line = line " "
                    else if (b == "0")             line = line esc "[" ct "m▀"
                    else if (t == "0")             line = line esc "[" cb "m▄"
                    else if (t == b)               line = line esc "[" ct "m█"
                    else { bgc = cb; sub(/^38/, "48", bgc); line = line esc "[" ct ";" bgc "m▀" }
                }
                print line esc "[0m"
            }
        }' "$assets/cat.pix" | put "$out/fastfetch-logo.ansi"
    cols=$(head -n 1 "$assets/cat.pix" | tr -d '\n' | wc -c)
    rows=$(( $(wc -l < "$assets/cat.pix") / 2 ))
fi

name=$(printf %s "${LR_THEME:-lovelyrice}" | tr -cd 'A-Za-z0-9._ -')
ver=$(cat "$assets/../VERSION" 2>/dev/null | tr -cd '0-9A-Za-z.-')
if [ "$cols" -gt 0 ]; then
    logo=$(printf '  "logo": { "type": "file-raw", "source": "%s/fastfetch-logo.ansi", "width": %s, "height": %s, "padding": { "top": 1, "right": 3 } },' "$out" "$cols" "$rows")
else
    logo='  "logo": { "type": "small" },'
fi
cat <<EOF | put "$out/fastfetch.jsonc"
{
  "\$schema": "https://github.com/fastfetch-cli/fastfetch/raw/dev/doc/json_schema.json",
$logo
  "display": {
    "separator": "  ",
    "color": { "keys": "$(sgr "$accent")", "title": "$(sgr "$accent2")", "separator": "$(sgr "$dim")" }
  },
  "modules": [
    "title",
    { "type": "separator", "string": "─" },
    { "type": "os", "key": "os" },
    { "type": "kernel", "key": "kernel" },
    { "type": "uptime", "key": "uptime" },
    { "type": "packages", "key": "packages" },
    { "type": "shell", "key": "shell" },
    { "type": "wm", "key": "wm" },
    { "type": "terminal", "key": "terminal" },
    { "type": "cpu", "key": "cpu" },
    { "type": "gpu", "key": "gpu" },
    { "type": "memory", "key": "memory" },
    { "type": "disk", "key": "disk", "folders": "/" },
    { "type": "custom", "key": "rice", "format": "lovelyrice ${ver:-?}  ·  $name" },
    "break",
    { "type": "colors", "symbol": "block" }
  ]
}
EOF

exit 0
